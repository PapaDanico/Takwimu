#!/usr/bin/env node
// Writes docs/editorial/REVIEW_QUEUE.md: every value awaiting editorial review, high-stakes first (fiscal
// discrepancies, then audit findings, then health indicators), with counts per dataset. Generated from
// lib/review-status.js and data/reviews.json; scripts/test-reviews.js fails the build when the file is stale.
// Output is deterministic (no clock): the date shown is data/reviews.json meta.updated.
// Run: node scripts/review-queue.js            (write the file)
//      node scripts/review-queue.js --dataset counties-cob   (print that dataset's full pending list to stdout)
const fs = require('fs');
const path = require('path');
const rs = require('../lib/review-status');
// Machine cross-checks (data/machine-checks.json): values whose second machine reading disagrees go first. A machine
// check never changes a value's state; it only orders the queue.
let MACHINE = { checks: [] };
try { MACHINE = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', 'machine-checks.json'), 'utf8')); } catch (e) { /* not generated */ }

const PRIORITY = {
  1: 'Priority 1: fiscal discrepancies',
  2: 'Priority 2: audit findings',
  3: 'Priority 3: health indicators',
  4: 'Priority 4: other fiscal values and calculations',
  5: 'Priority 5: other statistics and records',
};
const LISTED = [1, 2, 3]; // listed item by item; 4 and 5 are summarised (use --dataset for the full list)
const esc = (t) => String(t == null ? '' : t).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function pending() {
  const out = [];
  rs.DATASET_IDS.forEach((d) => rs.observations(d).forEach((o) => {
    const s = rs.stateOf(d, o.id);
    if (s.state === 'REVIEW_PENDING' || (s.state === 'DISPUTED' && !s.record)) out.push({ dataset: d, ...o, state: s.state, anchored: s.anchored, reason: s.reason });
  }));
  // High-stakes first; disputed before plain pending; then dataset and id, so the order is stable.
  return out.sort((a, b) => a.priority - b.priority || (a.state === b.state ? 0 : a.state === 'DISPUTED' ? -1 : 1) || a.dataset.localeCompare(b.dataset) || a.id.localeCompare(b.id, 'en', { numeric: true }));
}

function render() {
  const items = pending();
  const L = [];
  L.push('# Editorial review queue');
  L.push('');
  L.push(`Generated by \`node scripts/review-queue.js\` from \`data/reviews.json\` (updated ${rs.reviews.meta.updated}) and \`lib/review-status.js\`. Do not edit by hand; the build fails when this file is out of date.`);
  L.push('');
  L.push('Procedure: [review-sop.md](review-sop.md). Every value below is public and labelled "Provisional: awaiting editorial review" until a review record in `data/reviews.json` names it. "Unanchored" means the value has no source document with a stored SHA-256, so it cannot be approved until the document is acquired and hashed (stop condition (b)).');
  L.push('');
  const disagree = (MACHINE.checks || []).filter((c) => c.result === 'disagree').sort((a, b) => a.dataset.localeCompare(b.dataset) || a.id.localeCompare(b.id, 'en', { numeric: true }));
  const mc = (MACHINE.checks || []).reduce((c, x) => { c[x.result] = (c[x.result] || 0) + 1; return c; }, {});
  L.push(`## First: machine cross-check disagrees (${disagree.length})`);
  L.push('');
  L.push(`A second machine reading of the source page, by a different method from the original extraction (\`data/machine-checks.json\`, \`scripts/machine-check.js\`), did not find these values. Check them first. A machine check is not editorial review: it never approves or rejects a value, and no review record may cite it. Results for ${(MACHINE.checks || []).length} Siaya values: ${mc.agree || 0} agree, ${mc.disagree || 0} disagree, ${mc['not checkable'] || 0} not checkable. Review packs: [packs/](packs/).`);
  L.push('');
  if (disagree.length) {
    L.push('| Dataset | Record id | Source document | PDF page | Second method |');
    L.push('|---|---|---|---:|---|');
    disagree.forEach((c) => L.push(`| ${c.dataset} | \`${esc(c.id)}\` | ${esc(c.source_id)} | ${c.pdf_page} | ${esc(c.method)} |`));
  } else L.push('None.');
  L.push('');
  L.push('## Counts per dataset');
  L.push('');
  L.push('| Dataset | Values | Approved | Pending | Rejected | Disputed | Superseded | Unanchored |');
  L.push('|---|---:|---:|---:|---:|---:|---:|---:|');
  const tot = { total: 0, approved: 0, pending: 0, rejected: 0, disputed: 0, superseded: 0, unanchored: 0 };
  rs.DATASET_IDS.forEach((d) => {
    const c = rs.counts(d);
    Object.keys(tot).forEach((k) => { tot[k] += c[k]; });
    L.push(`| ${d} | ${c.total} | ${c.approved} | ${c.pending} | ${c.rejected} | ${c.disputed} | ${c.superseded} | ${c.unanchored} |`);
  });
  L.push(`| **All** | **${tot.total}** | **${tot.approved}** | **${tot.pending}** | **${tot.rejected}** | **${tot.disputed}** | **${tot.superseded}** | **${tot.unanchored}** |`);
  L.push('');
  L.push(`Review records in force: ${rs.inForce.length} (of ${rs.reviews.decisions.length} in the file).`);
  L.push('');
  L.push('Not itemised (registers and map layers, not measured values):');
  L.push('');
  Object.entries(rs.NOT_ITEMISED).forEach(([k, v]) => L.push(`- \`${k}\`: ${v}`));
  L.push('');
  [1, 2, 3, 4, 5].forEach((p) => {
    const group = items.filter((i) => i.priority === p);
    L.push(`## ${PRIORITY[p]} (${group.length})`);
    L.push('');
    if (!group.length) { L.push('Nothing pending.'); L.push(''); return; }
    const per = {};
    group.forEach((i) => { per[i.dataset] = per[i.dataset] || { n: 0, disputed: 0, unanchored: 0, kinds: new Set() }; per[i.dataset].n += 1; if (i.state === 'DISPUTED') per[i.dataset].disputed += 1; if (!i.anchored) per[i.dataset].unanchored += 1; per[i.dataset].kinds.add(i.kind); });
    L.push('| Dataset | Pending | Disputed | Unanchored | What |');
    L.push('|---|---:|---:|---:|---|');
    Object.entries(per).forEach(([d, v]) => L.push(`| ${d} | ${v.n} | ${v.disputed} | ${v.unanchored} | ${esc([...v.kinds].join('; '))} |`));
    L.push('');
    if (LISTED.includes(p)) {
      L.push('| Dataset | Record id | Value | Source document(s) | State |');
      L.push('|---|---|---|---|---|');
      group.forEach((i) => L.push(`| ${i.dataset} | \`${esc(i.id)}\` | ${esc(i.label)} | ${esc(i.sources.join(', ')) || '(none)'} | ${i.state === 'DISPUTED' ? 'disputed' : 'pending'}${i.anchored ? '' : ', unanchored'} |`));
    } else {
      L.push(`Full list for one dataset: \`node scripts/review-queue.js --dataset <dataset>\`.`);
    }
    L.push('');
  });
  return `${L.join('\n').replace(/\n+$/, '')}\n`;
}

module.exports = { render, pending };

if (require.main === module) {
  const i = process.argv.indexOf('--dataset');
  if (i > 0) {
    const d = process.argv[i + 1];
    if (!rs.DATASET_IDS.includes(d)) { console.error(`Unknown dataset ${d}. One of: ${rs.DATASET_IDS.join(', ')}`); process.exit(1); }
    pending().filter((x) => x.dataset === d).forEach((x) => console.log(`${x.id}\t${x.state}\t${x.sources.join(',')}\t${x.label}`));
  } else {
    const file = path.join(__dirname, '..', 'docs', 'editorial', 'REVIEW_QUEUE.md');
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, render());
    console.log(`Wrote ${path.relative(process.cwd(), file)} (${pending().length} values pending)`);
  }
}
