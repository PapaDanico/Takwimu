#!/usr/bin/env node
// Writes the review packs (owner item 1a, 23 Nov 2026): docs/editorial/packs/<dataset>.md for people and
// data/review-packs.json for machines. One entry per Siaya-scope value (lib/review-pack.js): record id, stored value,
// unit and period, source title, address, SHA-256, PDF and printed page, the text as printed or read, the other
// sources' values for the same measure and period, the machine cross-check result, and a review-record template whose
// decision and reviewer_role are blank. A pack prepares review; it is not review and changes no value's state.
// Deterministic (no clock). Run: node scripts/review-packs.js        Check only: node scripts/review-packs.js --check
const fs = require('fs');
const path = require('path');
const pack = require('../lib/review-pack');

const ROOT = path.join(__dirname, '..');
let MACHINE = { checks: [] };
try { MACHINE = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'machine-checks.json'), 'utf8')); } catch (e) { /* not generated */ }
const MC = Object.fromEntries((MACHINE.checks || []).map((c) => [`${c.dataset}|${c.id}`, c]));
const esc = (t) => String(t == null ? '' : t).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const show = (v) => (v === null || v === undefined ? '(none)' : typeof v === 'object' ? JSON.stringify(v) : String(v));

// county: a county in lib/county-registry.js other than Siaya (lib/county-review.js); its packs go to its own files
// (registry review paths) and Siaya's packs are untouched.
function build(county) {
  const counties = county ? require('../lib/county-registry') : null;
  const cr = county ? require('../lib/county-review') : null;
  let mc = MC;
  if (county) { mc = {}; try { JSON.parse(fs.readFileSync(counties.abs(counties.COUNTY_DATA[county].review.machine_checks), 'utf8')).checks.forEach((c) => { mc[`${c.dataset}|${c.id}`] = c; }); } catch (e) { /* not generated */ } }
  const all = county ? cr.entries(county) : pack.all();
  const entries = all.map((e) => {
    const m = mc[`${e.dataset}|${e.id}`];
    return {
      dataset: e.dataset, record_id: e.id, label: e.label, kind: e.kind, state: e.state,
      value: e.value, unit: e.unit, period: e.period, scope: e.scope,
      source: e.source.map((s) => ({ id: s.id, title: s.title, url: s.url, sha256: s.sha256 })),
      pdf_page: e.pdf_page, printed_page: e.printed_page, read: e.read, printed_text: e.printed_text, note: e.note,
      others: e.others,
      machine_check: m ? { result: m.result, method: m.method, matched: m.matched || null, reason: m.reason || null } : null,
      template: pack.template(e),
    };
  });
  const json = {
    meta: {
      title: county ? `Review packs: every ${county[0].toUpperCase()}${county.slice(1)} value with what a reviewer needs to check it (county not yet on pages)` : 'Review packs: every Siaya-scope value with what a reviewer needs to check it',
      rule: 'Preparation for editorial review, not review. The template\'s decision and reviewer_role are blank and must be filled by an independent reviewer (not the extractor) following docs/editorial/review-sop.md; nothing here is copied into data/reviews.json by a script. A machine cross-check result is not a basis for a review decision.',
      generated_by: 'scripts/review-packs.js',
      scope: county ? `Every value in ${counties.COUNTY_DATA[county].layout} (fiscal ledger, audit opinions, population); the county's rows of data/counties-cob.json are reused inside its ledger.` : 'Every dataset about Siaya; the 47-county Controller of Budget file for Siaya\'s rows only; the IMF file (national) is out of scope.',
      counts: county ? cr.counts(county) : pack.scopeCount(),
      total: entries.length,
    },
    entries,
  };
  const md = {};
  (county ? cr.datasets(county) : pack.SCOPE).forEach((ds) => {
    const list = entries.filter((x) => x.dataset === ds);
    const L = [];
    L.push(`# Review pack: ${ds}`);
    L.push('');
    if (county) L.push(`Generated by \`node scripts/review-packs.js --county ${county}\` (do not edit by hand). ${list.length} values. Procedure: [../../review-sop.md](../../review-sop.md). ${county[0].toUpperCase()}${county.slice(1)} is not yet on pages (lib/county-registry.js NOT_YET_ON_PAGES): nothing here is published, and data/reviews.json holds no record for it.`);
    else L.push(`Generated by \`node scripts/review-packs.js\` (do not edit by hand). ${list.length} values. Procedure: [../review-sop.md](../review-sop.md). The queue: [../REVIEW_QUEUE.md](../REVIEW_QUEUE.md).`);
    L.push('');
    L.push('Each value lists what was stored, where it was read, the text as printed (or as read by OCR), the other sources for the same measure and period, and the result of the independent machine cross-check. The review-record template has `decision` and `reviewer_role` blank: an independent reviewer (never the extractor) fills them after opening the page, and adds the record to `data/reviews.json`. A machine cross-check is not review and may not be cited as the basis of a decision.');
    L.push('');
    const dis = list.filter((x) => x.machine_check && x.machine_check.result === 'disagree');
    if (dis.length) { L.push(`Machine check disagrees (check these first): ${dis.map((x) => `\`${x.record_id}\``).join(', ')}.`); L.push(''); }
    list.forEach((x) => {
      L.push(`## \`${x.record_id}\`: ${esc(x.label)}`);
      L.push('');
      L.push(`- Stored value: ${esc(show(x.value))}${x.unit ? ` (${esc(x.unit)})` : ''}; period ${esc(show(x.period))}${x.scope ? `; scope ${esc(x.scope)}` : ''}`);
      x.source.forEach((s) => L.push(`- Source: ${esc(s.title)}${s.url ? ` <${s.url}>` : ''}; SHA-256 ${s.sha256 ? `\`${s.sha256}\`` : 'none (no stored copy: cannot be approved, stop condition (b))'}`));
      L.push(`- Page: ${x.pdf_page != null ? `PDF p. ${esc(x.pdf_page)}` : 'not recorded'}${x.printed_page != null ? ` (printed p. ${esc(x.printed_page)})` : ''}; read by ${esc(x.read || 'not recorded')}`);
      L.push(`- As printed or read: ${x.printed_text ? `"${esc(x.printed_text)}"` : '(no string stored)'}`);
      if (x.note) L.push(`- Note: ${esc(x.note)}`);
      L.push(`- Other sources, same measure and period: ${x.others.length ? x.others.map((o) => `${esc(show(o.value))} ${esc(o.unit || '')} (\`${o.id}\`, ${esc(o.source)}${o.pdf_page != null ? ` p. ${o.pdf_page}` : ''})`).join('; ') : 'none'}`);
      L.push(`- Machine cross-check: ${x.machine_check ? `${x.machine_check.result}${x.machine_check.method ? ` (${x.machine_check.method})` : ''}${x.machine_check.matched ? `, found "${esc(x.machine_check.matched)}"` : ''}${x.machine_check.reason ? `; ${esc(x.machine_check.reason)}` : ''}` : 'not run'}`);
      L.push(`- Current state: ${esc(x.state)}`);
      L.push('');
      L.push('```json');
      L.push(JSON.stringify(x.template));
      L.push('```');
      L.push('');
    });
    md[ds] = `${L.join('\n').replace(/\n+$/, '')}\n`;
  });
  return { json: `${JSON.stringify(json, null, 1)}\n`, md };
}

module.exports = { build };

if (require.main === module) {
  const ci = process.argv.indexOf('--county');
  const county = ci > 0 ? process.argv[ci + 1] : null;
  const { json, md } = build(county);
  const reg = county ? require('../lib/county-registry').COUNTY_DATA[county].review : null;
  const dir = county ? path.join(ROOT, reg.packs_md) : path.join(ROOT, 'docs', 'editorial', 'packs');
  const jsonFile = county ? path.join(ROOT, reg.packs_json) : path.join(ROOT, 'data', 'review-packs.json');
  const files = { [jsonFile]: json, ...Object.fromEntries(Object.entries(md).map(([ds, t]) => [path.join(dir, `${ds}.md`), t])) };
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([f, t]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== t).map(([f]) => path.relative(ROOT, f));
    if (stale.length) { console.error(`review-packs: out of date (run node scripts/review-packs.js): ${stale.join(', ')}`); process.exit(1); }
    console.log(`review-packs: up to date (${Object.keys(md).length} packs)`);
  } else {
    fs.mkdirSync(dir, { recursive: true });
    Object.entries(files).forEach(([f, t]) => fs.writeFileSync(f, t));
    console.log(`review-packs: wrote ${Object.keys(md).length} packs to ${path.relative(ROOT, dir)}/ and ${path.relative(ROOT, jsonFile)}`);
  }
}
