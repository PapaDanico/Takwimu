export function t(key, lang = "sheng") {
  const entry = SHENG[key];
  if (!entry) return key;
  return entry[lang] || entry.en;
}

export function toggleLang(current) {
  return current === "sheng" ? "en" : "sheng";
}

export function detectLang(text) {
  const markers = ["budaa", "msee", "wasee", "poa", "noma", "chanua", "iko", "haiko", "haina", "sawa", "niaje", "uko", "aje", "vipi", "nini", "hii", "hiyo", "zile", "hizo", "mulla", "tot", "shida", "suluhu", "biashara", "hustle", "ground", "kweli"];
  const lower = text.toLowerCase();
  const matches = markers.filter((w) => lower.includes(w)).length;
  return matches >= 2 ? "sheng" : "en";
}

